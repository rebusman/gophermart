-- Состояние планировщика повторных проверок расчёта начислений.
--
-- Обе колонки принадлежат фоновому процессу, а не заказу: наружу они не
-- отдаются, в контракт API не входят и никем, кроме воркера, не читаются.
-- Поэтому они добавляются здесь, вместе с воркером, а не в миграции 000002
-- вместе с заказом.
--
-- Колонка accrual здесь не добавляется: она создана миграцией 000002 и всё
-- это время оставалась NULL. Благодаря этому изменение меняет только то, кто
-- пишет в неё значение, а не формат ответа GET /api/user/orders.
--
-- Значения по умолчанию константны, поэтому начиная с PostgreSQL 11
-- добавление колонок не переписывает таблицу: миграция дёшева независимо от
-- числа накопленных заказов. Отдельного шага заполнения не требуется —
-- next_attempt_at по умолчанию равен now(), и все ранее загруженные заказы
-- становятся доступны для проверки сразу после старта.

ALTER TABLE orders
    ADD COLUMN attempts        INTEGER     NOT NULL DEFAULT 0,
    ADD COLUMN next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now();

ALTER TABLE orders
    ADD CONSTRAINT orders_attempts_nonnegative CHECK (attempts >= 0);

-- Индекс под выборку заданий фоновым процессом.
--
-- Индекс частичный: заказы в окончательных состояниях повторно не
-- опрашиваются и в выборку не попадают никогда, а со временем составляют
-- подавляющее большинство строк таблицы. Условие индекса дословно повторяет
-- условие запроса выборки, поэтому планировщик может им воспользоваться.
--
-- Порядок по next_attempt_at повторяет ORDER BY запроса: задания берутся
-- начиная с тех, что ждут дольше всех.
CREATE INDEX orders_pending_next_attempt_idx
    ON orders (next_attempt_at)
    WHERE status IN ('NEW', 'PROCESSING');
