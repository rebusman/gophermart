-- Списания баллов лояльности в счёт оплаты заказов.
--
-- Первичный ключ композитный и совпадает с требуемым предметной областью
-- ограничением уникальности «у одного пользователя не более одного списания
-- по одному номеру заказа». Суррогатный ключ добавил бы второй индекс, не
-- давая ничего: на списание никто не ссылается — журнала движений баллов в
-- схеме нет, а эндпоинта адресации отдельного списания нет в контракте.
--
-- Уникальность действует в пределах пользователя, а не глобально. Это не
-- послабление, а требование корректности: набор кодов ответа
-- POST /api/user/balance/withdraw не содержит кода «номер занят другим
-- пользователем», поэтому глобальное ограничение либо превращало бы законное
-- списание второго пользователя в 500, либо — при ON CONFLICT DO NOTHING —
-- молча не выполняло бы его, вернув клиенту успех без списания.
--
-- Внешнего ключа на orders нет: номер заказа в списании гипотетический, он
-- проверяется алгоритмом Луна, но не обязан существовать среди загруженных
-- заказов. Тип TEXT и по той же причине, что в orders: длина номера ничем не
-- ограничена, арифметика над ним не выполняется, а ведущий ноль значим.
--
-- Колонка называется sum, а не amount: так имя колонки, имя поля DTO и имя
-- поля JSON совпадают, и на пути от тела запроса до строки таблицы не
-- возникает переименования. Ключевым словом sum в PostgreSQL не является и
-- кавычек не требует.

CREATE TABLE withdrawals (
    user_id         UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    order_number    TEXT NOT NULL,
    sum             NUMERIC(18, 2) NOT NULL,
    processed_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    PRIMARY KEY (user_id, order_number),

    CONSTRAINT withdrawals_sum_positive CHECK (sum > 0)
);

-- Индекс под выдачу истории списаний пользователя от новых к старым.
--
-- Состав и порядок сортировки повторяют ORDER BY запроса чтения целиком,
-- включая второй ключ: без order_number DESC индекс задавал бы порядок лишь
-- до совпадающих меток времени, и группы строк с одинаковым processed_at
-- пришлось бы досортировывать.
--
-- Первичный ключ этот индекс не заменяет: он упорядочен по номеру заказа
-- внутри пользователя, а история читается по времени списания.
CREATE INDEX withdrawals_user_processed_at_idx
    ON withdrawals (user_id, processed_at DESC, order_number DESC);
