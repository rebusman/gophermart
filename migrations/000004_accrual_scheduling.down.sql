-- Откат состояния планировщика повторных проверок.
--
-- Частичный индекс и ограничение неотрицательности построены на удаляемых
-- колонках и удаляются вместе с ними, поэтому отдельных операторов для них не
-- требуется.
--
-- Колонка accrual не трогается: она принадлежит миграции 000002, и её удаление
-- здесь нарушило бы контракт чтения заказа.

ALTER TABLE orders
    DROP COLUMN IF EXISTS next_attempt_at,
    DROP COLUMN IF EXISTS attempts;
