-- Заказы, загруженные пользователями для расчёта начислений.
--
-- Номер заказа служит первичным ключом: он уникален глобально по требованию
-- предметной области, неизменен на протяжении жизни заказа и участвует в
-- каждом обращении к заказу. Суррогатный ключ добавил бы второй индекс и
-- лишний переход, не давая ничего сверх этого.
--
-- Тип TEXT, а не числовой: длина номера ничем не ограничена и легко выходит за
-- пределы BIGINT, над номером не выполняется арифметика, а ведущий ноль
-- значим.
--
-- Колонка accrual создаётся здесь и остаётся NULL до появления фонового
-- расчёта: начисление описывает сам заказ, а не состояние воркера, и входит в
-- контракт чтения заказа. Отсутствие значения и ноль по контракту не
-- эквивалентны, поэтому колонка допускает NULL и не имеет значения по
-- умолчанию.

CREATE TABLE orders (
    number          TEXT PRIMARY KEY,
    user_id         UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status          TEXT NOT NULL,
    accrual         NUMERIC(18, 2),
    uploaded_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT orders_status_known CHECK (status IN ('NEW', 'PROCESSING', 'INVALID', 'PROCESSED'))
);

-- Индекс под выдачу списка заказов пользователя от новых к старым.
--
-- Состав и порядок сортировки повторяют ORDER BY запроса чтения целиком,
-- включая второй ключ. Без number DESC индекс задавал бы порядок лишь до
-- совпадающих меток времени, и группы строк с одинаковым uploaded_at
-- пришлось бы досортировывать (Incremental Sort в плане запроса).
--
-- Индекс делает бессортировочный план доступным, но не обязательным: между
-- упорядоченным обходом индекса и выборкой по битовой карте с последующей
-- сортировкой планировщик по-прежнему выбирает по стоимости.
CREATE INDEX orders_user_uploaded_at_idx ON orders (user_id, uploaded_at DESC, number DESC);
